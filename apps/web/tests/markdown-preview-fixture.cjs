// Disposable local + SSH repositories for Markdown UI acceptance.
// Build shared, ssh-client, server and web before running this file.
const fs = require('node:fs');
const path = require('node:path');
const { createServer } = require('node:http');
const { createHash } = require('node:crypto');
const {
  createRepository,
} = require('../../../packages/ssh-client/tests/helpers/local-repository.cjs');
const { startSSHServer } = require('../../../packages/ssh-client/tests/helpers/ssh-server.cjs');

async function createMarkdownFixture() {
  const fixture = createRepository();
  const previousDir = process.env.ALUNE_DATA_DIR;
  process.env.ALUNE_DATA_DIR = path.join(fixture.root, 'app-data');
  const { startServer } = require('../../server/dist/bootstrap');
  const { ConnectionService } = require('../../server/dist/connection/connection.service');
  const { RepositoryService } = require('../../server/dist/repository/repository.service');
  const content = fs.readFileSync(path.join(__dirname, 'fixtures/markdown-preview.md'), 'utf8');
  const png = Buffer.from(
    'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a5WQAAAAASUVORK5CYII=',
    'base64',
  );
  fixture.write('README.md', content);
  fixture.write(
    'docs/guide.MD',
    '# 子文档\n\n[返回 README](../README.md#资源规则)\n\n## 中文标题\n\n相对资源：![共享图片](../assets/sample.png)\n',
  );
  fixture.write('empty.md', '');
  fixture.write('whitespace.md', ' \n\t');
  fixture.write('huge.md', '# Too large\n' + 'x'.repeat(1024 * 1024));
  fixture.write('large.md', '# Large\n' + 'x'.repeat(256 * 1024));
  fixture.write('slow.md', '# 慢速文档\n\n旧请求不能覆盖新文件。\n');
  fixture.write('assets/sample.png', png);
  fixture.write('assets/vector.svg', '<svg xmlns="http://www.w3.org/2000/svg"/>');
  fixture.write('assets/broken.png', 'not an image');
  fixture.write(
    'badges.md',
    '# 图片回退\n\n[![外部徽章](https://example.invalid/tracker.png)](https://example.com/)\n\n![损坏图片](assets/broken.png)\n',
  );
  fixture.write(
    'wide.md',
    '# 窄窗口\n\n```text\n' +
      'long_code_'.repeat(120) +
      '\n```\n\n| ' +
      Array(14).fill('列标题').join(' | ') +
      ' |\n| ' +
      Array(14).fill('---').join(' | ') +
      ' |\n| ' +
      Array(14).fill('表格内容').join(' | ') +
      ' |\n\n![宽图片](assets/wide.png)\n',
  );
  // A wide PNG generated by the existing rasterizer, with no extra test dependency.
  const { Resvg } = require('@resvg/resvg-js');
  fixture.write(
    'assets/wide.png',
    new Resvg(
      '<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="160"><rect width="1600" height="160" fill="#4080bf"/></svg>',
    )
      .render()
      .asPng(),
  );
  if (process.platform !== 'win32')
    fs.symlinkSync('sample.png', path.join(fixture.repo, 'assets/link.png'));
  fixture.git('add', '.');
  fixture.git('commit', '-qm', 'Markdown preview fixture');

  const remote = await startSSHServer();
  const app = await startServer({
    port: 0,
    host: '127.0.0.1',
    webRoot: path.resolve(__dirname, '../dist'),
  });
  const connections = app.get(ConnectionService);
  const connection = await connections.create({
    ...remote.options,
    name: 'Markdown SSH 验收',
    authType: 'password',
  });
  const repositories = app.get(RepositoryService);
  const local = await repositories.addLocal(fixture.repo);
  const ssh = await repositories.add(connection.id, fixture.repo);
  const state = { requests: [], version: 1, fail: false, slowMs: 1200 };
  const originalRead = repositories.readFile.bind(repositories);
  repositories.readFile = async (id, file) => {
    state.requests.push({ id, path: file });
    if (file === 'slow.md') await new Promise((resolve) => setTimeout(resolve, state.slowMs));
    if (state.fail && file === 'README.md') throw new Error('Markdown fixture read failure');
    return originalRead(id, file);
  };
  const digest = () =>
    createHash('sha256')
      .update(fs.readFileSync(path.join(fixture.repo, 'README.md')))
      .digest('hex');
  const control = createServer(async (req, res) => {
    let text = '';
    for await (const part of req) text += part;
    const body = JSON.parse(text || '{}');
    if (body.version) {
      state.version = body.version;
      fixture.write('README.md', content + `\n\n## 刷新版本 ${body.version}\n`);
      // Same image path, different bytes and dimensions after refresh.
      fixture.write(
        'assets/sample.png',
        body.version === 1 ? png : fs.readFileSync(path.join(fixture.repo, 'assets/wide.png')),
      );
    }
    if ('fail' in body) state.fail = body.fail;
    if ('slowMs' in body) state.slowMs = body.slowMs;
    if (body.resetRequests) state.requests.length = 0;
    res.writeHead(200, { 'Content-Type': 'application/json' }).end(
      JSON.stringify({
        ...state,
        digest: digest(),
        status: fixture.git('status', '--porcelain'),
      }),
    );
  });
  await new Promise((resolve) => control.listen(0, '127.0.0.1', resolve));
  const url = await app.getUrl();
  return {
    localUrl: `${url}/repositories/${local.id}`,
    sshUrl: `${url}/repositories/${ssh.id}`,
    controlUrl: `http://127.0.0.1:${control.address().port}`,
    repo: fixture.repo,
    async close() {
      control.closeAllConnections();
      await new Promise((resolve) => control.close(resolve));
      await app.close();
      await remote.close();
      fixture.close();
      if (previousDir === undefined) delete process.env.ALUNE_DATA_DIR;
      else process.env.ALUNE_DATA_DIR = previousDir;
    },
  };
}

module.exports = { createMarkdownFixture };
if (require.main === module)
  createMarkdownFixture()
    .then((fixture) => {
      console.log(
        'MARKDOWN_UI_FIXTURE ' +
          JSON.stringify({
            localUrl: fixture.localUrl,
            sshUrl: fixture.sshUrl,
            controlUrl: fixture.controlUrl,
            repo: fixture.repo,
          }),
      );
      for (const signal of ['SIGINT', 'SIGTERM'])
        process.once(signal, () => fixture.close().then(() => process.exit()));
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
